"""The local-LLM path, tested against a fake Ollama server (no model needed)."""
import httpx
import pytest

from app.core.config import get_settings
from app.graph.builder import ArchitectureGraph
from app.rag import llm
from app.rag.answerability import load_answerability_model
from app.rag.answerer import NOT_FOUND, GroundedAnswerer
from app.rag.retriever import BM25Retriever

CHUNKS = [{"chunk_id": "c1", "text": "DoorControl provides IDoorStatus to BodyControlManager.",
           "page_number": 2, "section": "4. Interfaces"}]
Q = "Which component provides IDoorStatus?"


class Resp:
    def __init__(self, data):
        self._data = data

    def raise_for_status(self):
        pass

    def json(self):
        return self._data


def tags(*names):
    return Resp({"models": [{"name": n} for n in names]})


def chat(text):
    return Resp({"message": {"role": "assistant", "content": text}})


@pytest.fixture
def setup(monkeypatch):
    s = get_settings()
    monkeypatch.setattr(s, "llm_provider", "ollama")
    monkeypatch.setattr(s, "llm_model", "llama3.2")
    monkeypatch.setattr(s, "answerability_model_dir", "/nonexistent")
    load_answerability_model.cache_clear()
    llm._cache.update(at=0.0, status=None)
    answerer = GroundedAnswerer(BM25Retriever(CHUNKS), ArchitectureGraph(), "doc", "v1")
    yield monkeypatch, answerer
    llm._cache.update(at=0.0, status=None)
    load_answerability_model.cache_clear()


def test_llm_is_used_labelled_and_grounded(setup):
    mp, answerer = setup
    seen = {}

    def post(url, json=None, **kw):
        seen["url"], seen["body"] = url, json
        return chat("DoorControl provides IDoorStatus [C1].")

    mp.setattr(httpx, "get", lambda *a, **kw: tags("llama3.2:latest"))
    mp.setattr(httpx, "post", post)
    r = answerer.answer(Q)
    assert r.answer == "DoorControl provides IDoorStatus [C1]." and r.generated_by == "ollama:llama3.2"
    assert seen["url"].endswith("/api/chat") and seen["body"]["options"]["temperature"] == 0
    system, user = seen["body"]["messages"]
    assert "ONLY" in system["content"] and "DoorControl provides IDoorStatus" in user["content"]
    assert r.citations and any("generated by ollama" in lim for lim in r.limitations)


def test_unfaithful_answer_is_rejected(setup):
    mp, answerer = setup
    mp.setattr(httpx, "get", lambda *a, **kw: tags("llama3.2:latest"))
    mp.setattr(httpx, "post", lambda *a, **kw: chat("GhostManager provides IDoorStatus [C1]."))
    r = answerer.answer(Q)
    assert r.generated_by is None and "Relevant document text" in r.answer
    assert any("faithfulness" in lim for lim in r.limitations)


def test_ollama_not_running_falls_back(setup):
    mp, answerer = setup

    def refuse(*a, **kw):
        raise httpx.ConnectError("refused")

    mp.setattr(httpx, "get", refuse)
    r = answerer.answer(Q)
    assert r.generated_by is None and "Relevant document text" in r.answer
    assert any("not reachable" in lim for lim in r.limitations)


def test_model_not_installed_gives_clear_message(setup):
    mp, answerer = setup
    mp.setattr(httpx, "get", lambda *a, **kw: tags("mistral:latest"))
    status = llm.llm_status(force=True)
    assert status.reachable and not status.model_installed and "ollama pull llama3.2" in status.detail
    assert answerer.answer(Q).generated_by is None


def test_not_found_reply_and_server_error_fall_back(setup):
    mp, answerer = setup
    mp.setattr(httpx, "get", lambda *a, **kw: tags("llama3.2:latest"))
    mp.setattr(httpx, "post", lambda *a, **kw: chat(NOT_FOUND))
    assert answerer.answer(Q).generated_by is None

    def boom(*a, **kw):
        raise httpx.ReadTimeout("slow")

    mp.setattr(httpx, "post", boom)
    llm._cache.update(at=0.0, status=None)
    assert answerer.answer(Q).generated_by is None


def test_local_provider_never_touches_network(monkeypatch):
    def forbidden(*a, **kw):
        raise AssertionError("no network call expected when LLM_PROVIDER=local")

    monkeypatch.setattr(httpx, "get", forbidden)
    monkeypatch.setattr(httpx, "post", forbidden)
    monkeypatch.setattr(get_settings(), "llm_provider", "local")
    a = GroundedAnswerer(BM25Retriever(CHUNKS), ArchitectureGraph(), "doc", "v1")
    assert a.answer(Q).generated_by is None


def test_faithfulness_guard_unit():
    ev = "DoorControl provides IDoorStatus. BodyControlManager uses DoorStatus_In."
    assert llm.is_faithful("DoorControl provides IDoorStatus [C1].", ev, "q")
    assert llm.is_faithful("It uses DoorStatus_In.", ev, "q")
    assert not llm.is_faithful("WindowControl uses it.", ev, "q")
